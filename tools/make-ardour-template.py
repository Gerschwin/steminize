#!/usr/bin/env python3
"""Captures the pieces of an Ardour session that Send to DAW fills in, as src/export/ardourTemplate.ts.

Run it only when Ardour's session format changes (it is written for Ardour 8 / 9, session version 7003):

  1. Make a clean session:   ardour9-new_session -s 44100 -m 2 /tmp/Base Base
  2. Find a stereo audio track made by Ardour (any real session with a plain stereo track, no plugins).
  3. python3 tools/make-ardour-template.py /tmp/Base/Base.ardour OTHER.ardour "Track name"

The skeleton keeps everything Ardour wrote for a new session (config, ports, the Master bus) and marks where the song's sources,
regions, playlists, locations, tempo map and routes go. The track template is that stereo track with its names, ids and mixer values
turned into placeholders. Nothing from the donor session's music is kept: only the structure.
"""
import json, re, sys
import xml.etree.ElementTree as ET

base_path, donor_path, track_name = sys.argv[1:4]

# ---- the skeleton ----
text = open(base_path, encoding='utf-8').read()
text = re.sub(r'(<Session [^>]*?)uuid="[^"]*"', r'\1uuid="{{UUID}}"', text, count=1)
text = re.sub(r'(<Session [^>]*?) name="[^"]*"', r'\1 name="{{SESSION}}"', text, count=1)
text = re.sub(r'id-counter="\d+"', 'id-counter="{{IDCOUNTER}}"', text, count=1)
for tag, token in [('Sources', '{{SOURCES}}'), ('Regions', '{{REGIONS}}'), ('Locations', '{{LOCATIONS}}'), ('Playlists', '{{PLAYLISTS}}')]:
    assert f'<{tag}/>' in text, tag
    text = text.replace(f'<{tag}/>', token, 1)
assert '</Routes>' in text
text = text.replace('</Routes>', '{{ROUTES}}</Routes>', 1)
text, n = re.subn(r'<TempoMap .*?</TempoMap>', '{{TEMPOMAP}}', text, count=1, flags=re.S)
assert n == 1
skeleton = text

# ---- the stereo track ----
root = ET.parse(donor_path).getroot()
route = [r for r in root.find('Routes') if r.get('name') == track_name][0]
for port in route.iter('Port'):
    for ext in list(port.findall('ExtConnection')):
        port.remove(ext)  # hardware connections belong to the donor's sound card
ET.indent(route)
s = ET.tostring(route, encoding='unicode')
ids = sorted({m for m in re.findall(r'\bid="(\d+)"', s)}, key=int)
mapping = {old: f'{{{{I{i}}}}}' for i, old in enumerate(ids)}
s = re.sub(r'\bid="(\d+)"', lambda m: f'id="{mapping[m.group(1)]}"', s)
s = re.sub(r'audio-playlist="\d+"', 'audio-playlist="{{PLAYLIST}}"', s)
s = s.replace(track_name, '{{NAME}}')
s = re.sub(r'(<PresentationInfo order=")\d+(" flags="[^"]*" color=")\d+(")', r'\1{{ORDER}}\2{{COLOR}}\3', s)
s = re.sub(r'(<MuteMaster [^>]*muted=")\d(")', r'\1{{MUTED}}\2', s)
s = re.sub(r'(<Controllable name="mute" [^>]*value=")\d(")', r'\1{{MUTED}}\2', s)
s = re.sub(r'(<Controllable name="solo" [^>]*value=")\d(" self-solo=")\d(")', r'\1{{SOLO}}\2{{SOLO}}\3', s)
s = re.sub(r'(<Controllable name="gaincontrol" [^>]*value=")[^"]*(")', r'\1{{GAIN}}\2', s)
s = re.sub(r'(<Controllable name="pan-azimuth" [^>]*value=")[^"]*(")', r'\1{{PAN}}\2', s)
route_tpl = s
assert '{{NAME}}' in route_tpl and '{{GAIN}}' in route_tpl and '{{PAN}}' in route_tpl and '{{PLAYLIST}}' in route_tpl

# ---- a region, with its fades, from the donor's first playlist ----
pl = next(p for p in root.find('Playlists') if len(p))
region = pl[0]
for ev in region.iter('events'):
    pass
region_ids = sorted({m for m in re.findall(r'\bid="(\d+)"', ET.tostring(region, encoding='unicode'))}, key=int)

out = f'''// Generated by tools/make-ardour-template.py from Ardour 9.7 (session version 7003): do not edit by hand.
// The skeleton is what Ardour writes for a new session, with places marked for the song's parts; the route is a stereo audio track
// with its names, ids and mixer values turned into placeholders ({{{{NAME}}}}, {{{{I0}}}} and so on).

export const ARDOUR_SKELETON = {json.dumps(skeleton)};

export const ARDOUR_ROUTE = {json.dumps(route_tpl)};

/** How many distinct ids the route template uses (the placeholders {{{{I0}}}} to {{{{I{len(ids)-1}}}}}). */
export const ARDOUR_ROUTE_IDS = {len(ids)};
'''
open('src/export/ardourTemplate.ts', 'w').write(out)
print('skeleton', len(skeleton), 'route', len(route_tpl), 'ids', len(ids))
